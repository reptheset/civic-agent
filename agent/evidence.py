"""Evidence pack: a PDF showing what was submitted, where each value came from, and how it was verified."""
import hashlib
from xml.sax.saxutils import escape

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Image, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from agent.config import RECEIPT_DIR


def _t(s) -> str:
    # Built-in PDF fonts have no rupee glyph
    return escape(str(s if s is not None else "")).replace("₹", "Rs. ")


def build_evidence_pdf(rec: dict, state: dict) -> tuple[str, str]:
    path = RECEIPT_DIR / f"{rec['run_id']}_evidence.pdf"
    ss = getSampleStyleSheet()
    small = ParagraphStyle("small", parent=ss["BodyText"], fontSize=8, leading=10)
    h1, h2 = ss["Title"], ss["Heading2"]

    def table(rows, widths):
        t = Table([[Paragraph(_t(c), small) for c in r] for r in rows], colWidths=widths, repeatRows=1)
        t.setStyle(TableStyle([("GRID", (0, 0), (-1, -1), 0.25, colors.grey),
                               ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#e2e8f0")),
                               ("VALIGN", (0, 0), (-1, -1), "TOP")]))
        return t

    story = [Paragraph("Application Evidence Pack", h1),
             Paragraph(_t("Generated by Civic Agent. Portal: CivicTest Scholarship Portal "
                          "(team-built test environment, not a government website)."), small),
             Spacer(1, 4 * mm)]

    # 1. Acknowledgement
    story += [Paragraph("1. Acknowledgement", h2), table([
        ["Field", "Value"],
        ["Application ID", rec.get("application_id")],
        ["Verified on portal page", "Yes" if rec.get("verified_on_page") else "NO"],
        ["Status", rec.get("status")],
        ["Captured at", rec.get("captured_at")],
        ["Portal URL", rec.get("url")],
        ["Screenshot SHA-256", rec.get("screenshot_sha256")],
        ["Run ID", rec.get("run_id")],
    ], [45 * mm, 125 * mm])]
    try:
        story += [Spacer(1, 3 * mm), Image(rec["screenshot"], width=170 * mm, height=95 * mm, kind="proportional")]
    except Exception:
        pass

    # 2. Eligibility
    g = state.get("guideline", {}) or {}
    story += [Paragraph("2. Eligibility check", h2),
              Paragraph(_t(f"Scheme: {g.get('name', '')}. Verdict: {state.get('verdict', '')}. "
                           f"Source: {g.get('url', '')}, fetched {g.get('fetched_at', '')} "
                           f"(SHA-256 {str(g.get('sha256', ''))[:24]}...). Rules discarded because their quote "
                           f"was not found in the source: {g.get('dropped', 0)}."), small),
              Spacer(1, 2 * mm)]
    rows = [["Result", "Rule", "Official quote"]]
    for r in state.get("eligibility", []) or []:
        rows.append([{True: "PASS", False: "FAIL", None: "REVIEW"}[r.get("passed")],
                     r.get("reason", ""), (r.get("rule") or {}).get("quote", "")])
    if len(rows) > 1:
        story.append(table(rows, [18 * mm, 55 * mm, 97 * mm]))

    # 3. Values and sources
    story += [Paragraph("3. Submitted values and their sources", h2),
              table([["Form field", "Value submitted"]] + [[l, v] for l, v in rec.get("review_rows", [])],
                    [70 * mm, 100 * mm])]
    prov = [["Profile field", "Source", "Confirmed by user"]]
    for k, f in sorted((state.get("profile") or {}).items()):
        p = f.get("provenance", {})
        prov.append([k, p.get("kind", "") + (f" ({p['document_type']})" if p.get("document_type") else ""),
                     "yes" if f.get("confirmed") else ("auto (matched document text)" if p.get("confidence", 0) >= 0.85 else "no")])
    story += [Spacer(1, 3 * mm), table(prov, [55 * mm, 80 * mm, 35 * mm])]

    # 4. Execution log
    steps = state.get("step_log", []) or []
    failed = sum(1 for s in steps if not s.get("ok"))
    retried = sum(1 for s in steps if s.get("recovery_rung", 0) > 0)
    story += [Paragraph("4. Execution log", h2),
              Paragraph(_t(f"{len(steps)} browser actions; {failed} failed checks, each followed by "
                           f"re-observation and re-planning; {retried} actions needed a retry. "
                           f"Final submission happened only after explicit user approval."), small),
              Spacer(1, 2 * mm)]
    rows = [["#", "Action", "Reference", "Result"]]
    for s in steps:
        a = s.get("action", {})
        rows.append([s.get("step"), f"{a.get('type')} el={a.get('element_id')}", a.get("value_ref") or "",
                     ("OK: " if s.get("ok") else "FAILED: ") + str(s.get("verify_note", ""))])
    story.append(table(rows, [10 * mm, 35 * mm, 45 * mm, 80 * mm]))

    SimpleDocTemplate(str(path), pagesize=A4, leftMargin=20 * mm, rightMargin=20 * mm, topMargin=15 * mm,
                      bottomMargin=15 * mm, title=f"Evidence pack {rec.get('application_id')}").build(story)
    return str(path), hashlib.sha256(path.read_bytes()).hexdigest()
